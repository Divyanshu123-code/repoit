def test_filter_repository_with_fixture(fixture_repo: Path) -> None:
    """Test full repository scanning on the fixture repo."""
    file_filter = RepoFileFilter(
        max_file_size_bytes=50 * 1024,  # 50 KB cap
        allowed_extensions={".py"},
        check_content_secrets=True,
    )

    summary: RepoFilterSummary = file_filter.filter_repository(fixture_repo)

    assert summary.total_scanned > 0
    accepted_paths = [p.as_posix() for p in summary.accepted_files]

    # Valid python files must be accepted
    assert "src/main.py" in accepted_paths
    assert "src/utils.py" in accepted_paths
    assert "tests/test_main.py" in accepted_paths

    # Binary files must NOT be in accepted
    assert "assets/logo.png" not in accepted_paths
    assert "src/compiled.pyc" not in accepted_paths
    assert "src/nullbyte.dat" not in accepted_paths

    # Vendor files must NOT be in accepted
    assert "node_modules/pkg/index.js" not in accepted_paths
    assert ".venv/lib/site.py" not in accepted_paths
    assert "build/lib/generated.py" not in accepted_paths

    # Generated files must NOT be in accepted
    assert "static/bundle.min.js" not in accepted_paths
    assert "poetry.lock" not in accepted_paths
    assert "src/autogen_service.py" not in accepted_paths

    # Secrets must NOT be in accepted
    assert ".env" not in accepted_paths
    assert ".env.production" not in accepted_paths
    assert "certs/server.pem" not in accepted_paths
    assert "certs/id_rsa" not in accepted_paths
    assert "src/leaky_config.py" not in accepted_paths

    # Large file must NOT be in accepted
    assert "src/huge_data.py" not in accepted_paths


def test_individual_reasons_in_skipped_files(fixture_repo: Path) -> None:
    """Verify each skipped file has the expected specific FilterReason."""
    file_filter = RepoFileFilter(
        max_file_size_bytes=50 * 1024,
        allowed_extensions={".py"},
        check_content_secrets=True,
    )

    summary = file_filter.filter_repository(fixture_repo)
    reasons_by_path = {res.path.as_posix(): res.reason for res in summary.skipped_files}

    # Verify specific reasons
    assert reasons_by_path.get("assets/logo.png") == FilterReason.BINARY_FILE
    assert reasons_by_path.get("src/compiled.pyc") == FilterReason.BINARY_FILE
    assert reasons_by_path.get("src/nullbyte.dat") == FilterReason.BINARY_FILE

    assert reasons_by_path.get(".env") == FilterReason.SECRET_FILE
    assert reasons_by_path.get(".env.production") == FilterReason.SECRET_FILE
    assert reasons_by_path.get("certs/server.pem") == FilterReason.SECRET_FILE
    assert reasons_by_path.get("certs/id_rsa") == FilterReason.SECRET_FILE
    assert reasons_by_path.get("src/leaky_config.py") == FilterReason.SECRET_FILE

    assert reasons_by_path.get("static/bundle.min.js") == FilterReason.GENERATED_FILE
    assert reasons_by_path.get("poetry.lock") == FilterReason.GENERATED_FILE
    assert reasons_by_path.get("src/autogen_service.py") == FilterReason.GENERATED_FILE

    assert reasons_by_path.get("src/huge_data.py") == FilterReason.SIZE_EXCEEDED


