# Regex patterns for detecting high-risk secrets inside file contents
SECRET_CONTENT_REGEXES: tuple[re.Pattern[str], ...] = (
    # Private Key blocks
    re.compile(r"-----BEGIN (?:[A-Z0-9_-]+\s)?PRIVATE KEY-----"),
    # AWS access keys
    re.compile(r"(?:A3T[A-Z0-9]|AKIA|AGPA|AIDA|AROA|AIPA|ANPA|ANVA|ASIA)[A-Z0-9]{16}"),
    # GitHub personal access tokens
    re.compile(r"(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9_]{36,255}|github_pat_[a-zA-Z0-9_]{82}"),
    # GitLab tokens
    re.compile(r"glpat-[a-zA-Z0-9_\-]{20,255}"),
    # Slack tokens
    re.compile(r"xox[baprs]-[0-9a-zA-Z]{10,48}"),
    # Google API Key
    re.compile(r"AIza[0-9A-Za-z\\-_]{35}"),
    # OpenAI & Anthropic API Keys
    re.compile(
        r"sk-[a-zA-Z0-9]{20,T3BlbkFJ[a-zA-Z0-9]{20,}|sk-proj-[a-zA-Z0-9_\-]{40,}|sk-ant-(?:api\d{2}-)?[a-zA-Z0-9_\-]{32,}"
    ),
    # JWT Tokens
    re.compile(r"\beyJ[a-zA-Z0-9_-]{10,}\.eyJ[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}\b"),
    # Generic high-confidence API key / secret assignment in code
    re.compile(
        r"""(?i)(?:api[_-]?key|secret[_-]?key|auth[_-]?token|client[_-]?secret|access[_-]?token|password)\s*[:=]\s*['"][a-zA-Z0-9_\-]{16,}['"]"""
    ),
)

# Markers in file headers that denote generated code
GENERATED_HEADER_MARKERS: tuple[str, ...] = (
    "@generated",
    "auto-generated",
    "automatically generated",
    "code generated by",
    "do not edit",
    "do not modify",
)


class RepoFileFilter:
    """Configurable scanner that accepts or rejects files in a repository."""

    def __init__(
        self,
        max_file_size_bytes: int | None = None,
        allowed_extensions: set[str] | None = None,
        vendor_dirs: set[str] | None = None,
        check_content_secrets: bool = True,
    ) -> None:
        settings = get_settings()
        self.max_file_size_bytes = (
            max_file_size_bytes
            if max_file_size_bytes is not None
            else settings.REPO_MAX_FILE_SIZE_BYTES
        )
        self.allowed_extensions = (
            {ext.lower() for ext in allowed_extensions} if allowed_extensions else None
        )
        self.vendor_dirs = set(DEFAULT_VENDOR_DIRS if vendor_dirs is None else vendor_dirs)
        self.check_content_secrets = check_content_secrets

    def is_vendor_path(self, rel_path: Path) -> tuple[bool, str]:
        """Check if any directory segment in the relative path belongs to vendor/caches."""
        for part in rel_path.parts[:-1]:  # check directories only
            if part in self.vendor_dirs or part.endswith(".egg-info"):
                return True, f"Found vendor/cache directory '{part}' in path"
        return False, ""

    def is_secret_filename(self, filename: str) -> tuple[bool, str]:
        """Check if filename matches sensitive/secret patterns."""
        lower_name = filename.lower()
        for pattern in DEFAULT_SECRET_PATTERNS:
            if fnmatch.fnmatch(lower_name, pattern.lower()):
                return True, f"Matches sensitive file pattern '{pattern}'"
        return False, ""

    def is_generated_filename(self, filename: str) -> tuple[bool, str]:
        """Check if filename matches known generated/lockfile patterns."""
        lower_name = filename.lower()
        for pattern in DEFAULT_GENERATED_PATTERNS:
            if fnmatch.fnmatch(lower_name, pattern.lower()):
                return True, f"Matches generated/lockfile pattern '{pattern}'"
        return False, ""

    def is_binary(self, full_path: Path) -> bool:
        """Check if file has a binary extension or contains null bytes in its header."""
        ext = full_path.suffix.lower()
        if ext in DEFAULT_BINARY_EXTENSIONS:
            return True

        # Sniff first 8192 bytes for null byte
        try:
            with open(full_path, "rb") as f:
                header = f.read(8192)
                if b"\x00" in header:
                    return True
        except OSError:
            return True
        return False

    def is_generated_content(self, text_sample: str) -> bool:
        """Inspect the top lines of a file for autogenerated markers."""
        lines = text_sample.lower().splitlines()[:15]
        for line in lines:
            for marker in GENERATED_HEADER_MARKERS:
                if marker in line:
                    return True
        return False

    def contains_secrets(self, text_sample: str) -> tuple[bool, str]:
        """Scan text content against high-risk secret regex patterns."""
        for pattern in SECRET_CONTENT_REGEXES:
            if pattern.search(text_sample):
                return True, "Matches high-risk credential/token regex pattern"
        return False, ""

    def filter_file(self, repo_root: Path, file_path: Path) -> FilterResult:
        """Evaluate an individual file within a repository."""
        resolved_root = repo_root.resolve()
        resolved_file = file_path.resolve()

        # Symlink / path safety check
        if not resolved_file.is_relative_to(resolved_root):
            return FilterResult(
                path=file_path,
                is_accepted=False,
                reason=FilterReason.UNSAFE_PATH,
                detail="File resolves outside repository root",
            )

        try:
            rel_path = file_path.relative_to(repo_root)
        except ValueError:
            rel_path = Path(file_path.name)

        # 1. Vendor directory check
        is_vendor, vendor_msg = self.is_vendor_path(rel_path)
        if is_vendor:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.VENDOR_DIRECTORY,
                detail=vendor_msg,
            )

        # 2. Secret filename check
        is_secret, secret_msg = self.is_secret_filename(file_path.name)
        if is_secret:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.SECRET_FILE,
                detail=secret_msg,
            )

        # 3. Generated filename check
        is_gen, gen_msg = self.is_generated_filename(file_path.name)
        if is_gen:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.GENERATED_FILE,
                detail=gen_msg,
            )

        # 4. Stat & size cap check
        try:
            file_stat = file_path.lstat()
            # Reject symlinks to avoid circular loops or external file reads
            if stat.S_ISLNK(file_stat.st_mode):
                return FilterResult(
                    path=rel_path,
                    is_accepted=False,
                    reason=FilterReason.UNSAFE_PATH,
                    detail="Symlinks are not accepted for indexing",
                )
            size_bytes = file_stat.st_size
        except OSError as exc:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.UNSAFE_PATH,
                detail=f"Failed to read file attributes: {exc}",
            )

        if size_bytes > self.max_file_size_bytes:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.SIZE_EXCEEDED,
                detail=f"File size ({size_bytes} bytes) exceeds limit ({self.max_file_size_bytes} bytes)",
                size_bytes=size_bytes,
            )

        # 5. Binary check
        if self.is_binary(file_path):
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.BINARY_FILE,
                detail="Binary extension or null byte detected",
                size_bytes=size_bytes,
            )

        # 6. Extension filter (if restricted)
        if self.allowed_extensions is not None:
            ext = file_path.suffix.lower()
            if ext not in self.allowed_extensions:
                return FilterResult(
                    path=rel_path,
                    is_accepted=False,
                    reason=FilterReason.UNSUPPORTED_EXTENSION,
                    detail=f"Extension '{ext}' not in allowed set",
                    size_bytes=size_bytes,
                )

        # 7. Content-based checks (Generated header & embedded secrets)
        try:
            with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                content_sample = f.read(64 * 1024)  # First 64KB is sufficient for header & secrets

            if self.is_generated_content(content_sample):
                return FilterResult(
                    path=rel_path,
                    is_accepted=False,
                    reason=FilterReason.GENERATED_FILE,
                    detail="Generated code header marker detected in file content",
                    size_bytes=size_bytes,
                )

            if self.check_content_secrets:
                has_secret, secret_detail = self.contains_secrets(content_sample)
                if has_secret:
                    return FilterResult(
                        path=rel_path,
                        is_accepted=False,
                        reason=FilterReason.SECRET_FILE,
                        detail=secret_detail,
                        size_bytes=size_bytes,
                    )
        except OSError as exc:
            return FilterResult(
                path=rel_path,
                is_accepted=False,
                reason=FilterReason.UNSAFE_PATH,
                detail=f"Unable to read file content: {exc}",
                size_bytes=size_bytes,
            )

        # All checks passed
        return FilterResult(
            path=rel_path,
            is_accepted=True,
            reason=FilterReason.ACCEPTED,
            detail="File passed all filter checks",
            size_bytes=size_bytes,
        )

    def filter_repository(self, repo_root: Path) -> RepoFilterSummary:
        """Walk repo_root and classify all files."""
        summary = RepoFilterSummary()
        root_path = repo_root.resolve()

        for dirpath, dirnames, filenames in os.walk(root_path):
            current_dir = Path(dirpath)
            try:
                rel_dir = current_dir.relative_to(root_path)
            except ValueError:
                rel_dir = Path(".")

            # Prune vendor directories in-place from walk
            dirnames[:] = [
                d
                for d in dirnames
                if d not in self.vendor_dirs
                and not d.endswith(".egg-info")
                and not (rel_dir / d).as_posix().startswith(".")
            ]

            for fname in filenames:
                file_path = current_dir / fname
                summary.total_scanned += 1
                res = self.filter_file(root_path, file_path)
                if res.is_accepted:
                    summary.accepted_files.append(res.path)
                    summary.accepted_bytes += res.size_bytes
                else:
                    summary.skipped_files.append(res)
                    summary.skipped_bytes += res.size_bytes

        # Sort for deterministic output
        summary.accepted_files.sort()
        summary.skipped_files.sort(key=lambda r: str(r.path))
        return summary
