"""Repository file filter for ingestion pipelines (P1-03).

Filters out binaries, vendor directories, generated files, secrets,
and files exceeding size limits.
"""

import fnmatch
import logging
import os
import re
import stat
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path

from app.core.config import get_settings

logger = logging.getLogger("repopilot.repos.filter")


class FilterReason(str, Enum):
    """Reason why a file was accepted or skipped."""

    ACCEPTED = "accepted"
    BINARY_FILE = "binary_file"
    VENDOR_DIRECTORY = "vendor_directory"
    GENERATED_FILE = "generated_file"
    SECRET_FILE = "secret_file"
    SIZE_EXCEEDED = "size_exceeded"
    UNSUPPORTED_EXTENSION = "unsupported_extension"
    UNSAFE_PATH = "unsafe_path"


@dataclass(frozen=True)
class FilterResult:
    """Evaluation result for an individual file."""

    path: Path  # Path relative to repository root
    is_accepted: bool
    reason: FilterReason
    detail: str = ""
    size_bytes: int = 0


@dataclass
class RepoFilterSummary:
    """Summary of repository-wide filtering pass."""

    accepted_files: list[Path] = field(default_factory=list)
    skipped_files: list[FilterResult] = field(default_factory=list)
    total_scanned: int = 0
    accepted_bytes: int = 0
    skipped_bytes: int = 0


