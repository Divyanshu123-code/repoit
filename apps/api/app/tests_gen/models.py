"""SQLAlchemy models for AI generated test cases (P5-02).

Stores test cases generated by LLM with status 'unvalidated' prior to sandbox execution (P5-03).
Enforces:
    - Hard Rule 3: Repository content is untrusted; generated code is unvalidated.
    - Hard Rule 5: Source labelled strictly as 'llm_generated'.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base


class GeneratedTest(Base):
    """Represents an AI-synthesized unit or regression test case.

    Status lifecycle:
        'unvalidated' (P5-02 initial state) -> 'passed' | 'failed' | 'error' (P5-03 sandbox runner)
    """

    __tablename__ = "generated_tests"

    id: Mapped[uuid.UUID] = mapped_column(
        sa.UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    repository_id: Mapped[uuid.UUID] = mapped_column(
        sa.UUID(as_uuid=True),
        sa.ForeignKey("repositories.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    target_file: Mapped[str] = mapped_column(
        sa.String(1024),
        nullable=False,
        index=True,
    )
    target_symbol: Mapped[str | None] = mapped_column(
        sa.String(256),
        nullable=True,
        index=True,
    )
    finding_id: Mapped[uuid.UUID | None] = mapped_column(
        sa.UUID(as_uuid=True),
        sa.ForeignKey("static_findings.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    test_framework: Mapped[str] = mapped_column(
        sa.String(32),
        nullable=False,
        default="pytest",
    )
    test_name: Mapped[str] = mapped_column(
        sa.String(256),
        nullable=False,
        index=True,
    )
    test_code: Mapped[str] = mapped_column(
        sa.Text,
        nullable=False,
    )
    test_file_path: Mapped[str] = mapped_column(
        sa.String(1024),
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        sa.String(32),
        nullable=False,
        default="unvalidated",
        index=True,
    )  # 'unvalidated', 'passed', 'failed', 'error'
    error_message: Mapped[str | None] = mapped_column(
        sa.Text,
        nullable=True,
    )
    execution_output: Mapped[str | None] = mapped_column(
        sa.Text,
        nullable=True,
    )
    execution_duration_ms: Mapped[int | None] = mapped_column(
        sa.Integer,
        nullable=True,
    )
    source: Mapped[str] = mapped_column(
        sa.String(32),
        nullable=False,
        default="llm_generated",
    )  # Hard Rule 5: 'llm_generated'
    model_version: Mapped[str] = mapped_column(
        sa.String(64),
        nullable=False,
        default="gpt-4o-mini",
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
        onupdate=lambda: datetime.now(UTC),
    )

    def __init__(self, **kwargs: Any) -> None:
        if "source" not in kwargs:
            kwargs["source"] = "llm_generated"
        if "status" not in kwargs:
            kwargs["status"] = "unvalidated"
        if "test_framework" not in kwargs:
            kwargs["test_framework"] = "pytest"
        super().__init__(**kwargs)

    def to_dict(self) -> dict[str, Any]:
        """Convert test entity to JSON-serializable dictionary."""
        return {
            "id": str(self.id) if self.id else str(uuid.uuid4()),
            "repository_id": str(self.repository_id),
            "target_file": self.target_file,
            "target_symbol": self.target_symbol,
            "finding_id": str(self.finding_id) if self.finding_id else None,
            "test_framework": self.test_framework,
            "test_name": self.test_name,
            "test_code": self.test_code,
            "test_file_path": self.test_file_path,
            "status": self.status,
            "error_message": self.error_message,
            "execution_output": self.execution_output,
            "execution_duration_ms": self.execution_duration_ms,
            "source": self.source,
            "model_version": self.model_version,
            "created_at": (
                self.created_at.isoformat() if self.created_at else datetime.now(UTC).isoformat()
            ),
            "updated_at": (
                self.updated_at.isoformat() if self.updated_at else datetime.now(UTC).isoformat()
            ),
        }
